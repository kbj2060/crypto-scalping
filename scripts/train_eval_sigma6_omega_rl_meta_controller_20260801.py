#!/usr/bin/env python3
"""RL meta-controller for the Sigma6-filtered + Omega4.6.1 two-leg ETH portfolio (see
project-sigma6-regime-filter-leave-one-window-out-CANDIDATE-20260801.md and the same-day joint
portfolio check, research_eth_sigma6_walkforward_omega461_joint_portfolio_20260801.py).

RESEARCH PROTOTYPE ONLY -- explicitly requested by the user after being warned that:
(1) Omega4.7-RL (discrete SAC on raw entries) failed catastrophically (OOS -88~-99%) -- this
    project's only prior full-entry RL attempt;
(2) the two legs only produce 61 trades (VAL) + 98 trades (OOS) total, a small sample for any
    learned policy to generalize from;
(3) VAL_2025Q4 and OOS_2026H1 have both already been inspected repeatedly in this project's
    research history, so this evaluation is NOT a genuinely blind Fresh-Forward test per CLAUDE.md
    -- it is a research/dev score only, not a promotion or live-candidate claim.

Design: unlike Omega4.7-RL, this does NOT decide entries/exits -- those stay exactly as already
generated by the two existing, independently-validated signal generators (Omega4.6.1's live router,
Sigma6-filtered's regime-gated Sigma3-1h). The RL agent only learns a per-bar ALLOCATION WEIGHT in
[0, 1.5] for each leg's already-existing notional exposure -- i.e. "how much to lean into each leg's
current position this bar", including shrinking to ~0 during the 54 direction-conflict windows
found earlier this session (21 VAL + 33 OOS trade-pairs where the two legs are simultaneously long
and short). This is a far smaller, denser, less sparse decision problem than full entry timing,
which is exactly the axis Omega4.7-RL's failure was attributed to ("RL can't beat cost hurdle at
this sparsity").

State (hourly bars, matching the Sigma3-1h tape's native decision cadence): each leg's
active/side/unrealized-return/hold-fraction, the conflict flag, and the Sigma6 regime tape's own
bull/bear/chop probabilities + stability score (the same features the regime filter itself uses).
Reward: per-bar weighted dollar-PnL contribution to the combined equity curve, minus a drawdown-
shaping penalty (this project's SOL finding: pnl->log_risk objective change is what fixes MDD, see
project-sol-sidecar-mdd-unfixable-20260730.md) and an action-smoothness penalty to discourage
thrashing.

Training reuses the two legs' ALREADY-VALIDATED per-bar equity curves from
dump_sigma6_joint_portfolio_chart_data_20260801.py (which itself reproduces
research_eth_sigma6_walkforward_omega461_joint_portfolio_20260801.py's sanity-checked numbers
exactly) -- no re-derivation of the underlying trade mechanics. Trained on VAL_2025Q4 only
(replayed across multiple epochs, offline-RL-from-a-fixed-tape style, same precedent as this
project's other DSAC scripts e.g. train_eval_alpha6_1_dsac_risk_allocator_20260524.py), evaluated
frozen (no further learning) on OOS_2026H1.
"""
